"""Generate consumer symbol inventory from auth source; no release facts inferred."""
from pathlib import Path
import argparse
import re

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / 'docs/agents/api-inventory.md'


def render():
    lines = ['# API declaration inventory', '', 'Scope: Development/source. Generated by `python3 scripts/docs/inventory.py`.', '',
             'Read [API contracts](api.md) for ownership, errors and supported entry points.',
             'Public visibility alone does not make a screen helper a preferred integration API.', '']
    for file in sorted((ROOT / 'auth/src/main/java').rglob('*.kt')):
        text = file.read_text()
        declarations = []
        # Scan declaration prefixes, not constructor fields (a public class can
        # have private constructor properties). Preserve complete argument lists.
        masked = re.sub(r'""".*?"""|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*.*?\*/', lambda m: ' ' * len(m[0]), text, flags=re.S)
        pattern = r'^\s*((?:@\w+(?:\([^\n]*?\))?\s+)?(?:(?:public|private|internal|suspend|override|data|sealed|open|enum|annotation|value|const)\s+)*)(class|interface|object|fun)\s+'
        for match in re.finditer(pattern, text, re.M):
            if re.search(r'\b(private|internal)\b', match[1]):
                continue
            start = match.start()
            while text[start].isspace(): start += 1
            pos = match.end(); depth = 0
            while pos < len(masked):
                char = masked[pos]
                if char == '(': depth += 1
                elif char == ')': depth -= 1
                if depth == 0 and char in '{=\n':
                    # A multiline constructor/function can start on the next line.
                    if char == '\n' and masked[pos+1:].lstrip().startswith('('):
                        pos += 1; continue
                    break
                pos += 1
            declaration = text[start:pos].strip()
            declarations.append(declaration)
        if not declarations:
            continue
        path = file.relative_to(ROOT).as_posix()
        package = next(line for line in text.splitlines() if line.startswith('package '))
        lines.extend([f'## {file.stem}', '', f'[Source](../../{path})', '', '```kotlin', package, '', *declarations, '```', ''])
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            raise SystemExit('API inventory drift: run python3 scripts/docs/inventory.py')
    else:
        OUTPUT.write_text(expected)
